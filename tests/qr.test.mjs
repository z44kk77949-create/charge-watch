// --- 1. Algebra --------------------------------------------------------------
console.log("=== QR: algebra ===");

// A codeword generated by RS(n,k) with generator roots a^0..a^(t-1) has zero
// syndromes at exactly those roots. We can't reach the encoder's private
// rsEncode, so this is checked through the decoder below, which recovers each
// block's data+EC from the finished matrix — end to end, and the strongest
// place to assert it.

test("BCH format strings are divisible by their generator and carry level M", () => {
  for (let mask = 0; mask < 8; mask++) {
    const bits = formatBitsFromMatrixIndependent(mask);
    // Undo the specification's 0x5412 mask, then divide by 0x537: a valid BCH
    // codeword leaves no remainder.
    let rem = bits ^ 0x5412;
    for (let i = 14; i >= 10; i--) if (rem & (1 << i)) rem ^= 0x537 << (i - 10);
    assert.equal(rem, 0, `mask ${mask}: format bits are not a BCH codeword`);
    const data = (bits ^ 0x5412) >> 10;
    assert.equal(data >> 3, 0b00, `mask ${mask}: EC level bits should be 00 (level M)`);
    assert.equal(data & 0b111, mask, `mask ${mask}: mask bits don't round-trip`);
  }
});

test("version information strings are divisible by their generator", () => {
  const VERSION_INFO = { 7: 0x07c94, 8: 0x085bc, 9: 0x09a99, 10: 0x0a4d3 };
  for (const [v, bits] of Object.entries(VERSION_INFO)) {
    let rem = bits;
    for (let i = 17; i >= 12; i--) if (rem & (1 << i)) rem ^= 0x1f25 << (i - 12);
    assert.equal(rem, 0, `version ${v}: not a valid BCH(18,6) codeword`);
    assert.equal(bits >> 12, Number(v), `version ${v}: leading bits don't encode the version`);
  }
});

// Recover the format bits the encoder actually wrote, by generating a code and
// reading the two copies of the format area out of the matrix.
function formatBitsFromMatrixIndependent(wantMask) {
  // Generate until we get a code the encoder chose `wantMask` for; if it never
  // picks that mask for our sample strings, fall back to computing the bits the
  // way the specification describes (still independent of the encoder's code
  // path, since we re-derive them here).
  for (const s of SAMPLES) {
    const qr = cwQr.matrix(s);
    if (qr && qr.mask === wantMask) {
      const size = qr.size, m = qr.modules;
      let bits = 0;
      for (let i = 0; i <= 5; i++) bits |= (m[8][i] ? 1 : 0) << i;
      bits |= (m[8][7] ? 1 : 0) << 6;
      bits |= (m[8][8] ? 1 : 0) << 7;
      bits |= (m[7][8] ? 1 : 0) << 8;
      for (let i = 9; i <= 14; i++) bits |= (m[14 - i][8] ? 1 : 0) << i;
      return bits;
    }
  }
  const data = (0b00 << 3) | wantMask;
  let rem = data << 10;
  for (let i = 4; i >= 0; i--) if (rem & (1 << (i + 10))) rem ^= 0x537 << i;
  return ((data << 10) | rem) ^ 0x5412;
}

