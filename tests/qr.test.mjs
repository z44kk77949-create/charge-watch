  const svg = cwQr.svg("CW1:A-001:123456", { fg: "#101010", bg: "#fafafa" });
  assert.ok(svg.includes('fill="#fafafa"'), "background colour missing");
  assert.ok(svg.includes('fill="#101010"'), "foreground colour missing");
