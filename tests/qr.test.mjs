// QR encoder verification.
//
// The encoder in public/shared/qr.js is hand-written, so "it looks right" is not
// evidence. This suite checks it three ways that don't simply restate the
// encoder's own logic:
//
//   1. ALGEBRA — the Reed-Solomon codewords are verified by their syndromes
//      (a valid RS codeword evaluates to zero at a^1..a^n), and the BCH format
//      and version bit strings by divisibility by their generator polynomials.
//      These are properties of the mathematics, not of my code.
//   2. STRUCTURE — finder, timing, alignment and dark modules are checked
//      against the specification's fixed geometry.
//   3. ROUND TRIP — an independently written decoder (its own reserved-module
//      map, its own zigzag walk, its own de-interleaving) reads each generated
//      matrix back to the exact input string.
//
// If the encoder and this decoder ever shared a bug, the algebra checks would
// still catch a broken codeword, and the structure checks a broken layout.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import assert from "node:assert/strict";

const DIR = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(DIR, "..", "public", "shared", "qr.js"), "utf8");
const mod = { exports: {} };
new Function("module", "window", src)(mod, undefined);
const cwQr = mod.exports;

let failures = 0;
function test(name, fn) {
  try { fn(); console.log(`  ok   ${name}`); }
  catch (e) { failures++; console.error(`  FAIL ${name}\n       ${e.message}`); }
}

// --- GF(256), written independently of the encoder's copy --------------------
const EXP = new Array(512), LOG = new Array(256);
{
  let x = 1;
  for (let i = 0; i < 255; i++) { EXP[i] = x; LOG[x] = i; x <<= 1; if (x & 0x100) x ^= 0x11d; }
  for (let i = 255; i < 512; i++) EXP[i] = EXP[i - 255];
}
const mul = (a, b) => (a === 0 || b === 0 ? 0 : EXP[LOG[a] + LOG[b]]);

const VERSIONS = {
  1: [26, 10, 1, 16, 0, 0], 2: [44, 16, 1, 28, 0, 0], 3: [70, 26, 1, 44, 0, 0],
  4: [100, 18, 2, 32, 0, 0], 5: [134, 24, 2, 43, 0, 0], 6: [172, 16, 4, 27, 0, 0],
  7: [196, 18, 4, 31, 0, 0], 8: [242, 22, 2, 38, 2, 39], 9: [292, 22, 3, 36, 2, 37],
  10: [346, 26, 4, 43, 1, 44],
};
const ALIGN = {
  1: [], 2: [6, 18], 3: [6, 22], 4: [6, 26], 5: [6, 30],
  6: [6, 34], 7: [6, 22, 38], 8: [6, 24, 42], 9: [6, 26, 46], 10: [6, 28, 50],
};

